data class AccentPalette(
    val accent: Color,
    val ink: Color,
    val deep: Color,
    val soft: Color,
)

fun String.toComposeColor(): Color = try {
    Color(parseColor(this))
} catch (_: Exception) {
    Color(0xFFAAC7FF)
}

fun Accent.toPalette(): AccentPalette = AccentPalette(
    accent = accentHex.toComposeColor(),
    ink = inkHex.toComposeColor(),
    deep = deepHex.toComposeColor(),
    soft = softHex.toComposeColor(),
)

val DefaultAccent = AccentPalette(
